export const storyThemes = themes.map(theme => theme.name);
export const ageStories = themes.flatMap((theme, themeIndex) => storyAges.flatMap((age, ageIndex) => storyKinds.map((kind, kindIndex) => {
  const [title, situation, action] = theme.scenes[ageIndex];
  const character = ["小兔", "小鹿", "小安", "小晴"][ageIndex];
  const paragraphs = kind === "真實生活情境故事" ? [
    `生活情境：${situation}`, `如果是你，可以怎麼做？先停一下，觀察自己和身邊人的感受。`, `一種可能的做法：${action}。`, `和孩子一起討論：還有沒有其他可行的做法？不需要只有一個標準答案。`,
  ] : kind === "繪本" ? [
    `第一頁｜${character}的一天。${situation}`, `第二頁｜${character}停了一下。${ageIndex === 0 ? "大人蹲下來，用溫柔的聲音陪著。" : "心裡有一點猶豫，也有一點想試試看的勇氣。"}`,
    `第三頁｜${character}試著${action}。`, `第四頁｜事情不一定立刻變得完美，但${character}發現：可以${theme.lesson}。明天，還有一次練習的機會。`,
  ] : [
    `${character}原本以為，今天會是普通的一天。沒想到，${situation}`, `一開始，${character}不知道該怎麼辦。${ageIndex === 0 ? "大人靠近，陪著慢慢試。" : "深呼吸後，決定先做自己能做的一小步。"}`,
    `${character}決定${action}。這一小步，讓原本卡住的事情有了新的方向。`, `回想剛才的經過，${character}記住了一件事：${theme.lesson}。下次再遇到相似的事情，也可以找人一起練習。`,
  ];
  return { id: `story-${themeIndex}-${ageIndex}-${kindIndex}`, title: kind === "真實生活情境故事" ? `${title}：我會怎麼做？` : kind === "繪本" ? `${character}與${title}` : title, age, kind, theme: theme.name, color: theme.color, symbol: theme.symbol, paragraphs,
    prompts: ageIndex === 0 ? ["一起指一指：故事裡出現了誰？", "用表情或動作回應：他現在開心，還是需要抱抱？"] : [theme.question, "你有過類似的經驗嗎？下次可以找誰一起試試看？"],
    activity: ageIndex === 0 ? "由照顧者帶著做一次故事中的動作；孩子不想做時，可先觀察。" : `今天選一件小事，練習「${theme.lesson}」，結束後分享感受。`, minutes: [3, 5, 8, 10][ageIndex] };
})));
export type AgeStory = (typeof ageStories)[number];
